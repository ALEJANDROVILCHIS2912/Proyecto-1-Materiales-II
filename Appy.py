# -*- coding: utf-8 -*-
"""
Dashboard Interactivo - MPEA Dataset
App en Streamlit para explorar aleaciones de alta entropía.
"""

import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px

# =====================================================================
# CONFIGURACIÓN DE PÁGINA
# =====================================================================
st.set_page_config(
    page_title="MPEA Dashboard",
    page_icon="🔬",
    layout="wide",
    initial_sidebar_state="expanded"
)

# =====================================================================
# 1. CARGA Y LIMPIEZA DE DATOS
# =====================================================================
@st.cache_data
def cargar_datos():
    df = pd.read_excel("MPEA_dataset.xlsx", sheet_name=0)

    nuevos_nombres = {
        'FORMULA': 'Formula',
        'PROPERTY: Microstructure': 'Microestructura',
        'PROPERTY: Processing method': 'Metodo_Procesamiento',
        'PROPERTY: BCC/FCC/other': 'Estructura_Cristalina',
        'PROPERTY: grain size ($\\mu$m)': 'Tamano_Grano_um',
        'PROPERTY: Exp. Density (g/cm$^3$)': 'Densidad_Experimental',
        'PROPERTY: Calculated Density (g/cm$^3$)': 'Densidad_Calculada_g_cm3',
        'PROPERTY: HV': 'Dureza_HV',
        'PROPERTY: Test temperature ($^\\circ$C)': 'Temperatura_Test_C',
        'PROPERTY: YS (MPa)': 'Limite_Elastico_YS_MPa',
        'PROPERTY: UTS (MPa)': 'Resistencia_UTS_MPa',
        'PROPERTY: Elongation (%)': 'Elongacion_pct',
        'PROPERTY: Exp. Young modulus (GPa)': 'Young_Experimental_GPa',
        'PROPERTY: Calculated Young modulus (GPa)': 'Young_Calculado_GPa',
        'REFERENCE: year': 'Año',
        'REFERENCE: title': 'Titulo_Referencia'
    }
    df = df.rename(columns=nuevos_nombres)
    df = df.dropna(subset=['Formula'])
    return df


df_clean = cargar_datos()

# =====================================================================
# ENCABEZADO
# =====================================================================
st.title("🔬 Dashboard Interactivo de Muestras (MPEA)")
st.markdown(
    f"Análisis exploratorio del dataset de **aleaciones multicomponente** "
    f"con **{len(df_clean)} registros** cargados."
)
st.divider()

# =====================================================================
# MÉTRICAS RÁPIDAS
# =====================================================================
col1, col2, col3, col4 = st.columns(4)
col1.metric("📊 Total Muestras", len(df_clean))
col2.metric("🧪 Fórmulas Únicas", df_clean['Formula'].nunique())
col3.metric("🔬 Microestructuras", df_clean['Microestructura'].nunique())
col4.metric("📚 Publicaciones", df_clean['REFERENCE: doi'].nunique()
            if 'REFERENCE: doi' in df_clean.columns else "N/A")

st.divider()

# =====================================================================
# PESTAÑAS
# =====================================================================
tab_analisis, tab_buscador, tab_datos = st.tabs(
    ["📊 Análisis Visual", "🔍 Buscador Interactivo", "📋 Datos"]
)

# =====================================================================
# TAB 1: GRÁFICAS
# =====================================================================
with tab_analisis:
    st.header("📊 Análisis Visual del Dataset")

    # --- Filtro global para las gráficas ---
    with st.expander("⚙️ Filtros globales para las gráficas", expanded=False):
        col_f1, col_f2 = st.columns(2)
        with col_f1:
            micros_disponibles = sorted(
                df_clean['Microestructura'].dropna().unique().tolist()
            )
            micros_sel = st.multiselect(
                "Filtrar por Microestructura:",
                options=micros_disponibles,
                default=micros_disponibles
            )
        with col_f2:
            años_disp = sorted(
                df_clean['Año'].dropna().unique().astype(int).tolist()
            ) if 'Año' in df_clean.columns else []
            if años_disp:
                rango_años = st.slider(
                    "Rango de años:",
                    min_value=min(años_disp),
                    max_value=max(años_disp),
                    value=(min(años_disp), max(años_disp))
                )
            else:
                rango_años = None

    # Aplicar filtros
    df_graf = df_clean[df_clean['Microestructura'].isin(micros_sel)]
    if rango_años:
        df_graf = df_graf[
            (df_graf['Año'] >= rango_años[0]) & (df_graf['Año'] <= rango_años[1])
        ]

    st.caption(f"📌 Muestras tras filtros: **{len(df_graf)}**")

    # --- Gráfico 1: Densidad vs Dureza por microestructura ---
    st.subheader("1️⃣ Tendencia: Densidad vs Dureza por Microestructura")

    df_g1 = df_graf.dropna(
        subset=['Densidad_Calculada_g_cm3', 'Dureza_HV', 'Microestructura']
    )
    conteo = df_g1['Microestructura'].value_counts()
    grupos_validos = conteo[conteo > 5].index
    df_g1_f = df_g1[df_g1['Microestructura'].isin(grupos_validos)]

    if not df_g1_f.empty:
        fig1 = px.scatter(
            df_g1_f,
            x='Densidad_Calculada_g_cm3',
            y='Dureza_HV',
            color='Microestructura',
            trendline='ols',
            trendline_scope='trace',
            title='Densidad vs Dureza (líneas de tendencia OLS)',
            labels={
                'Densidad_Calculada_g_cm3': 'Densidad (g/cm³)',
                'Dureza_HV': 'Dureza (HV)'
            },
            template='plotly_white'
        )
        fig1.update_traces(marker=dict(size=0, opacity=0),
                           selector=dict(mode='markers'))
        st.plotly_chart(fig1, use_container_width=True)
    else:
        st.warning("No hay suficientes datos para este gráfico con los filtros actuales.")

    st.divider()

    # --- Gráfico 2: Boxplot Dureza por Método ---
    st.subheader("2️⃣ Distribución de Dureza por Método de Procesamiento")

    df_g2 = df_graf.dropna(subset=['Dureza_HV', 'Metodo_Procesamiento'])
    if not df_g2.empty:
        fig2 = px.box(
            df_g2,
            x='Metodo_Procesamiento',
            y='Dureza_HV',
            color='Metodo_Procesamiento',
            title='Dureza Vickers por Método de Procesamiento',
            labels={
                'Metodo_Procesamiento': 'Método',
                'Dureza_HV': 'Dureza (HV)'
            },
            template='plotly_white'
        )
        st.plotly_chart(fig2, use_container_width=True)
    else:
        st.warning("No hay datos suficientes para el boxplot.")

    st.divider()

    # --- Gráfico 3: Dureza vs YS por microestructura ---
    st.subheader("3️⃣ Tendencia: Dureza (HV) vs Límite Elástico (YS)")

    df_g3 = df_graf.dropna(
        subset=['Dureza_HV', 'Limite_Elastico_YS_MPa', 'Microestructura']
    )
    conteo3 = df_g3['Microestructura'].value_counts()
    grupos_validos3 = conteo3[conteo3 > 5].index
    df_g3_f = df_g3[df_g3['Microestructura'].isin(grupos_validos3)]

    if not df_g3_f.empty:
        fig3 = px.scatter(
            df_g3_f,
            x='Dureza_HV',
            y='Limite_Elastico_YS_MPa',
            color='Microestructura',
            trendline='ols',
            trendline_scope='trace',
            title='Dureza vs Límite Elástico (líneas de tendencia OLS)',
            labels={
                'Dureza_HV': 'Dureza (HV)',
                'Limite_Elastico_YS_MPa': 'Límite Elástico YS (MPa)'
            },
            template='plotly_white'
        )
        fig3.update_traces(marker=dict(size=0, opacity=0),
                           selector=dict(mode='markers'))
        st.plotly_chart(fig3, use_container_width=True)
    else:
        st.warning("No hay suficientes datos para este gráfico.")

# =====================================================================
# TAB 2: BUSCADOR INTERACTIVO
# =====================================================================
with tab_buscador:
    st.header("🔍 Buscador Interactivo de Muestras")
    st.markdown("Especifica los rangos para encontrar tu muestra ideal:")

    # Rangos
    dens_validas = df_clean['Densidad_Calculada_g_cm3'].dropna()
    durezas_validas = df_clean['Dureza_HV'].dropna()
    ys_validas = df_clean['Limite_Elastico_YS_MPa'].dropna()

    col_a, col_b = st.columns(2)

    with col_a:
        if not dens_validas.empty:
            rango_dens = st.slider(
                "Densidad (g/cm³):",
                min_value=float(dens_validas.min()),
                max_value=float(dens_validas.max()),
                value=(float(dens_validas.min()), float(dens_validas.max())),
                step=0.1
            )
        else:
            rango_dens = None

        if not durezas_validas.empty:
            rango_dureza = st.slider(
                "Dureza (HV):",
                min_value=float(durezas_validas.min()),
                max_value=float(durezas_validas.max()),
                value=(float(durezas_validas.min()), float(durezas_validas.max())),
                step=10.0
            )
        else:
            rango_dureza = None

    with col_b:
        if not ys_validas.empty:
            rango_ys = st.slider(
                "Límite Elástico YS (MPa):",
                min_value=float(ys_validas.min()),
                max_value=float(ys_validas.max()),
                value=(float(ys_validas.min()), float(ys_validas.max())),
                step=10.0
            )
        else:
            rango_ys = None

        micros_disponibles = ['Cualquiera'] + sorted(
            df_clean['Microestructura'].dropna().unique().tolist()
        )
        micro_sel = st.selectbox("Microestructura:", micros_disponibles)

    metodo_sel = st.selectbox(
        "Método de Procesamiento:",
        ['Cualquiera'] + sorted(
            df_clean['Metodo_Procesamiento'].dropna().unique().tolist()
        )
    )

    # Filtrado
    resultado = df_clean.copy()
    if rango_dens:
        resultado = resultado[
            resultado['Densidad_Calculada_g_cm3'].between(*rango_dens)
        ]
    if rango_dureza:
        resultado = resultado[resultado['Dureza_HV'].between(*rango_dureza)]
    if rango_ys:
        resultado = resultado[
            resultado['Limite_Elastico_YS_MPa'].between(*rango_ys)
        ]
    if micro_sel != 'Cualquiera':
        resultado = resultado[resultado['Microestructura'] == micro_sel]
    if metodo_sel != 'Cualquiera':
        resultado = resultado[resultado['Metodo_Procesamiento'] == metodo_sel]

    st.divider()
    st.success(f"🔍 Se encontraron **{len(resultado)}** muestras coincidentes.")

    if len(resultado) > 0:
        cols_mostrar = [c for c in [
            'Formula', 'Microestructura', 'Metodo_Procesamiento',
            'Densidad_Calculada_g_cm3', 'Dureza_HV',
            'Limite_Elastico_YS_MPa', 'Resistencia_UTS_MPa',
            'Elongacion_pct', 'Año'
        ] if c in resultado.columns]

        st.dataframe(
            resultado[cols_mostrar],
            use_container_width=True,
            hide_index=True
        )

        # Descarga CSV
        csv = resultado.to_csv(index=False).encode('utf-8')
        st.download_button(
            label="⬇️ Descargar resultados en CSV",
            data=csv,
            file_name="mpeas_filtradas.csv",
            mime="text/csv"
        )
    else:
        st.error("❌ No hay muestras con esos rangos. Intenta ampliarlos.")

# =====================================================================
# TAB 3: DATOS COMPLETOS
# =====================================================================
with tab_datos:
    st.header("📋 Explorador del Dataset Completo")
    st.markdown(f"Total de registros: **{len(df_clean)}**")

    # Selector de columnas
    todas_cols = df_clean.columns.tolist()
    cols_sel = st.multiselect(
        "Selecciona columnas a mostrar:",
        options=todas_cols,
        default=todas_cols[:8]
    )

    if cols_sel:
        st.dataframe(
            df_clean[cols_sel],
            use_container_width=True,
            hide_index=True,
            height=500
        )

    # Descarga completa
    csv_full = df_clean.to_csv(index=False).encode('utf-8')
    st.download_button(
        label="⬇️ Descargar dataset completo (CSV)",
        data=csv_full,
        file_name="MPEA_dataset_completo.csv",
        mime="text/csv"
    )

# =====================================================================
# FOOTER
# =====================================================================
st.divider()
st.caption("🔬 Dashboard MPEA — Desarrollado con Streamlit + Plotly")